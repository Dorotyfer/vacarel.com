CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, name VARCHAR(160) NOT NULL, username VARCHAR(190) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL, role VARCHAR(30) NOT NULL, active INTEGER NOT NULL DEFAULT 1,
 commission_rate DECIMAL(8,4) NOT NULL DEFAULT 0, commission_basis VARCHAR(20) NOT NULL DEFAULT 'collected'
);
CREATE TABLE IF NOT EXISTS products (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, code VARCHAR(80) NOT NULL UNIQUE, name VARCHAR(190) NOT NULL,
 box_size INTEGER NOT NULL DEFAULT 1, price DECIMAL(18,4) NOT NULL DEFAULT 0,
 average_cost DECIMAL(18,4) NOT NULL DEFAULT 0, min_stock INTEGER NOT NULL DEFAULT 0,
 tax INTEGER NOT NULL DEFAULT 10, track_expiry INTEGER NOT NULL DEFAULT 1, active INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS parties (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, kind VARCHAR(20) NOT NULL, name VARCHAR(190) NOT NULL,
 document VARCHAR(80) NOT NULL DEFAULT '', phone VARCHAR(80) NOT NULL DEFAULT '',
 address VARCHAR(255) NOT NULL DEFAULT '', credit_limit DECIMAL(18,4) NOT NULL DEFAULT 0,
 credit_days INTEGER NOT NULL DEFAULT 0, salesperson_id INTEGER NULL, active INTEGER NOT NULL DEFAULT 1,
 FOREIGN KEY(salesperson_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS lots (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, product_id INTEGER NOT NULL, supplier_id INTEGER NOT NULL,
 code VARCHAR(100) NOT NULL, expiry DATE NULL, quantity INTEGER NOT NULL,
 unit_cost DECIMAL(18,4) NOT NULL, purchase_tax INTEGER NULL, state VARCHAR(30) NOT NULL DEFAULT 'available',
 reference VARCHAR(190) NOT NULL, received_at VARCHAR(30) NOT NULL, user_id INTEGER NOT NULL,
 FOREIGN KEY(product_id) REFERENCES products(id), FOREIGN KEY(supplier_id) REFERENCES parties(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS movements (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, product_id INTEGER NOT NULL, lot_id INTEGER NOT NULL,
 quantity INTEGER NOT NULL, type VARCHAR(30) NOT NULL, reference VARCHAR(190) NOT NULL,
 created_at VARCHAR(30) NOT NULL, user_id INTEGER NOT NULL,
 FOREIGN KEY(product_id) REFERENCES products(id), FOREIGN KEY(lot_id) REFERENCES lots(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS operations (
 operation_key VARCHAR(100) PRIMARY KEY, payload_hash VARCHAR(64) NOT NULL, result_id INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS audit (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, user_id INTEGER NOT NULL, action VARCHAR(60) NOT NULL,
 resource VARCHAR(60) NOT NULL, resource_id INTEGER NOT NULL, before_data TEXT NULL, after_data TEXT NOT NULL, created_at VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS login_attempts (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, identity_hash VARCHAR(64) NOT NULL, attempted_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS billing_settings (
 id INTEGER PRIMARY KEY, payload TEXT NOT NULL, revision INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sales (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, operation_key VARCHAR(100) NOT NULL UNIQUE,
 payload_hash VARCHAR(64) NOT NULL, customer_id INTEGER NOT NULL, user_id INTEGER NOT NULL,
 number VARCHAR(30) NOT NULL, fiscal_key VARCHAR(100) NOT NULL UNIQUE,
 issued_on VARCHAR(10) NOT NULL, condition_name VARCHAR(10) NOT NULL, credit_days INTEGER NOT NULL,
 due_on VARCHAR(10) NOT NULL, total DECIMAL(18,0) NOT NULL, balance DECIMAL(18,0) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'invoiced', snapshot TEXT NOT NULL, created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY(customer_id) REFERENCES parties(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS sale_allocations (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, sale_id INTEGER NOT NULL, product_id INTEGER NOT NULL,
 lot_id INTEGER NOT NULL, quantity INTEGER NOT NULL, unit_cost DECIMAL(18,4) NOT NULL,
 FOREIGN KEY(sale_id) REFERENCES sales(id), FOREIGN KEY(product_id) REFERENCES products(id), FOREIGN KEY(lot_id) REFERENCES lots(id)
);
CREATE TABLE IF NOT EXISTS print_attempts (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, sale_id INTEGER NOT NULL, user_id INTEGER NOT NULL,
 request_key VARCHAR(100) NOT NULL UNIQUE, reason VARCHAR(255) NOT NULL,
 result VARCHAR(20) NOT NULL DEFAULT 'unknown', created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY(sale_id) REFERENCES sales(id), FOREIGN KEY(user_id) REFERENCES users(id)
);

