CREATE TABLE IF NOT EXISTS billing_settings (
 id INTEGER PRIMARY KEY, payload TEXT NOT NULL, revision INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sales (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, operation_key VARCHAR(100) NOT NULL UNIQUE,
 payload_hash VARCHAR(64) NOT NULL, customer_id INTEGER NOT NULL, user_id INTEGER NOT NULL,
 number VARCHAR(30) NOT NULL, fiscal_key VARCHAR(100) NOT NULL UNIQUE,
 issued_on VARCHAR(10) NOT NULL, condition_name VARCHAR(10) NOT NULL, credit_days INTEGER NOT NULL,
 due_on VARCHAR(10) NOT NULL, total DECIMAL(18,0) NOT NULL, balance DECIMAL(18,0) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'invoiced', snapshot TEXT NOT NULL, created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY(customer_id) REFERENCES parties(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS sale_allocations (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, sale_id INTEGER NOT NULL, product_id INTEGER NOT NULL,
 lot_id INTEGER NOT NULL, quantity INTEGER NOT NULL, unit_cost DECIMAL(18,4) NOT NULL,
 FOREIGN KEY(sale_id) REFERENCES sales(id), FOREIGN KEY(product_id) REFERENCES products(id), FOREIGN KEY(lot_id) REFERENCES lots(id)
);
CREATE TABLE IF NOT EXISTS print_attempts (
 id INTEGER PRIMARY KEY AUTO_INCREMENT, sale_id INTEGER NOT NULL, user_id INTEGER NOT NULL,
 request_key VARCHAR(100) NOT NULL UNIQUE, reason VARCHAR(255) NOT NULL,
 result VARCHAR(20) NOT NULL DEFAULT 'unknown', created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY(sale_id) REFERENCES sales(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
